def open_page_text(page_value, group_private_key):
    """A text as a lawyer's browser opens it from the clip page (keys/static/keys/clip_keys.js),
    with the group key; None if the page has none."""
    import base64
    import json

    from nacl import bindings
    from nacl.public import SealedBox

    from clips import vault
    if not page_value:
        return None
    sealed = json.loads(page_value)
    public_key = base64.b64encode(bytes(group_private_key.public_key)).decode()
    [sealed_key] = [item['sealed_data_key'] for item in sealed['sealed_keys'] if item['group_public_key'] == public_key]
    data_key = SealedBox(group_private_key).decrypt(base64.b64decode(sealed_key))
    encrypted = base64.b64decode(sealed['ciphertext'])
    padded = bindings.crypto_aead_xchacha20poly1305_ietf_decrypt(
        encrypted[vault.NONCE_BYTES:], base64.b64decode(sealed['additional_data']), encrypted[:vault.NONCE_BYTES], data_key,
    )
    return bindings.sodium_unpad(padded, vault.TEXT_BLOCK).decode()


def open_label(case, personal_private_key):
    """A case's label as the lawyer's browser opens it with their personal key (keys/static/keys/case_labels.js)."""
    import base64
    import json

    from nacl import bindings
    from nacl.public import SealedBox

    from cases import labels
    from clips import vault
    sealed = json.loads(labels.for_page(case))
    data_key = SealedBox(personal_private_key).decrypt(base64.b64decode(sealed['sealed_key']))
    encrypted = base64.b64decode(sealed['ciphertext'])
    padded = bindings.crypto_aead_xchacha20poly1305_ietf_decrypt(
        encrypted[vault.NONCE_BYTES:], base64.b64decode(sealed['additional_data']), encrypted[:vault.NONCE_BYTES], data_key,
    )
    return bindings.sodium_unpad(padded, vault.TEXT_BLOCK).decode()


def lawyer_text(clip, kind, group_private_key):
    """The clip's text as a lawyer's browser opens it, or None if there is none."""
    from cases.clip_pages import sealed_text_json
    return open_page_text(sealed_text_json(clip, kind), group_private_key)


def put_vault_file(clip, kind, source_path, extension):
    """Encrypt a file into the vault and record it as the clip's, as ingest does; returns its
    data key, which a lawyer's browser would open from its sealed key."""
    from clips import vault
    name, data_key = vault.store_file(clip, kind, source_path, extension)
    vault.record_file(clip, kind, name, data_key)
    return data_key


def open_data_key(clip, kind, group_private_key):
    """The file's data key, opened from its sealed key as a lawyer's browser does."""
    from nacl.public import SealedBox

    from clips.models import SealedKey
    sealed = SealedKey.objects.get(vault_file__clip=clip, vault_file__kind=kind, group_key__public_key=bytes(group_private_key.public_key))
    return SealedBox(group_private_key).decrypt(bytes(sealed.sealed_data_key))


def with_data_key(client, kind, data_key):
    """The cookie a hand-over sets (hand_over), set directly. Django's test client sends every
    cookie, whatever its path: tests/test_data_keys.py checks the path a browser keeps to."""
    from cases.clip_pages import COOKIES, cookie_value
    client.cookies[COOKIES[kind]] = cookie_value(data_key)
    return client


def hand_over(client, case, clip, kind, data_key):
    """What a clip page's script does: hand the file's data key over, for its cookie (cases.clip_pages)."""
    import base64

    from django.urls import reverse

    from clips import vault
    file = {vault.PROXY: 'proxy', vault.EVIDENCE_COPY: 'evidence-copy'}[kind]
    return client.post(
        reverse('lawyer:data_key', kwargs={'case_id': case.pk, 'clip_id': clip.pk, 'file': file}),
        {'data_key': base64.b64encode(data_key).decode()},
    )


def make_case(lawyer_profile, label='A case', rings=2, **fields):
    """A small case for `lawyer_profile`: one hour around a public place, with the default margin."""
    starts_at = timezone.now() - datetime.timedelta(days=30)
    values = {
        'starts_at': starts_at, 'ends_at': starts_at + datetime.timedelta(hours=1),
        'margin_minutes': 10, 'margin_rings': 1,
    }
    if 'cells' not in fields:
        values['cells'] = grid.widen([grid.cell_for_point(*BASTILLE, 11)], rings)
    # The label is sealed to the lawyer's personal key: one is made if they have none, as
    # admission requires since keys exist.
    from keys.grants import current_key
    if current_key(lawyer_profile) is None:
        make_key(lawyer_profile)
    return Case.objects.create_with_area(lawyer_profile, label, **{**values, **fields})

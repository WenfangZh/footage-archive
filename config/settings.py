def env_required(name):
    value = os.environ.get(name)
    if not value:
        raise ImproperlyConfigured(f'Set the {name} environment variable (see .env.example).')
    return value


def env_bool(name, default=False):
    value = os.environ.get(name)
    if value is None or value == '':
        return default
    if value.lower() in ('1', 'true', 'yes', 'on'):
        return True
    if value.lower() in ('0', 'false', 'no', 'off'):
        return False
    raise ImproperlyConfigured(f'{name} must be true or false, not {value!r}.')


def env_list(name):
    return [item.strip() for item in os.environ.get(name, '').split(',') if item.strip()]


def env_colour(name, default):
    """A colour as #rrggbb, checked here since it goes into a stylesheet."""
    value = os.environ.get(name) or default
    if not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
        raise ImproperlyConfigured(f'{name} must be a colour written #rrggbb, not {value!r}.')
    return value.lower()


def env_int(name, default, minimum=None, maximum=None):
    value = os.environ.get(name)
    if value is None or value == '':
        number = default
    else:
        try:
            number = int(value)
        except ValueError:
            raise ImproperlyConfigured(f'{name} must be a whole number, not {value!r}.') from None
    if minimum is not None and number < minimum:
        raise ImproperlyConfigured(f'{name} must be at least {minimum}, not {number}.')
    if maximum is not None and number > maximum:
        raise ImproperlyConfigured(f'{name} must be at most {maximum}, not {number}.')
    return number


